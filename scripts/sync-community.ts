// Copies phrases accepted by the phrase service into src/data/community-links.ts, so they become part of
// the built-in dictionary (and are checked by `pnpm validate:content`). Run nightly by GitHub Actions.
// Usage: pnpm sync:community   (reads VITE_COMMUNITY_API from the environment or .env.production)
import { readFileSync, writeFileSync } from 'node:fs'
import { COMMUNITY_LINKS } from '../src/data/community-links.ts'
import { LINKS } from '../src/data/links.ts'
import { communitySource, linkKey, parseLink } from '../src/lib/graph.ts'

const FILE = new URL('../src/data/community-links.ts', import.meta.url)

function apiAddress(): string {
  if (process.env.VITE_COMMUNITY_API) return process.env.VITE_COMMUNITY_API
  try {
    const env = readFileSync(new URL('../.env.production', import.meta.url), 'utf8')
    return /^VITE_COMMUNITY_API=(.*)$/m.exec(env)?.[1]?.trim() ?? ''
  } catch {
    return ''
  }
}

const api = apiAddress().replace(/\/+$/, '')
if (!api) {
  console.log('No VITE_COMMUNITY_API configured; nothing to sync.')
  process.exit(0)
}

const response = await fetch(`${api}/links`)
if (!response.ok) {
  console.error(`Phrase service answered ${response.status}; leaving community-links.ts unchanged.`)
  process.exit(1)
}
const body = (await response.json()) as { links?: unknown }
const fetched = Array.isArray(body.links) ? body.links.filter((item): item is string => typeof item === 'string') : []

const key = (source: string) => {
  const link = parseLink(source)
  return link ? linkKey(link.from, link.to) : null
}
const builtIn = new Set(LINKS.map(key))
const merged = new Map<string, string>()
for (const raw of [...COMMUNITY_LINKS, ...fetched]) {
  const source = communitySource(raw)
  const id = source ? key(source) : null
  if (!source || !id || builtIn.has(id) || merged.has(id)) continue
  merged.set(id, source)
}

const sources = [...merged.values()].sort((a, b) => (key(a) ?? '').localeCompare(key(b) ?? ''))
const added = sources.length - COMMUNITY_LINKS.length
const text = `// Phrases added from player suggestions after the phrase service confirmed them in Wiktionary.
// Generated by \`pnpm sync:community\` (run nightly by GitHub Actions); same format as LINKS in links.ts.
// To remove one: delete its line here AND add it to NEVER_LINKS in links.ts, or it will come back.
export const COMMUNITY_LINKS: readonly string[] = [
${sources.map(source => `  '${source}',`).join('\n')}${sources.length ? '\n' : ''}]
`
writeFileSync(FILE, text)
console.log(`Community phrases: ${sources.length} total (${added >= 0 ? `+${added}` : added} since last sync).`)
